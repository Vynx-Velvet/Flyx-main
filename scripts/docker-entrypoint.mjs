/**
 * Docker entrypoint for Flyx.
 *
 * 1. Ensures $FLYX_DATA_DIR/.env exists and holds JWT_SECRET and HOST_KEY,
 *    generating strong random values on first boot (file mode 0600).
 * 2. Loads that .env into the server environment (container env vars set via
 *    docker-compose / `docker run -e` win; process-control keys such as
 *    NODE_OPTIONS or PATH are never taken from the file).
 * 3. Execs `next start` and forwards SIGTERM/SIGINT.
 *
 * Mirrors the rules in packages/app/src/lib/security/env-safety.ts.
 */

import { spawn } from "child_process";
import { randomBytes } from "crypto";
import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync, chmodSync } from "fs";
import { createRequire } from "module";
import { isAbsolute, join } from "path";

const BLOCKED_KEY_PATTERNS = [
  /^NODE_/i,
  /^ELECTRON_/i,
  /^npm_/i,
  /^LD_/i,
  /^DYLD_/i,
  /^(PATH|PATHEXT|COMSPEC|SYSTEMROOT|WINDIR|TEMP|TMP|HOME|USERPROFILE|APPDATA|LOCALAPPDATA|PROGRAMDATA|SHELL)$/i,
  /^(UV_THREADPOOL_SIZE|OPENSSL_CONF|SSL_CERT_FILE|SSL_CERT_DIR)$/i,
  /^FLYX_(FFMPEG_PATH|STANDALONE_DIR|DATA_DIR|VLC_PATH|UPDATE_REPO|SERVER_HOST)$/i,
];
const ENV_KEY_RE = /^[A-Za-z_][A-Za-z0-9_]*$/;
const isBlocked = (k) => BLOCKED_KEY_PATTERNS.some((re) => re.test(k));

const dataDir = process.env.FLYX_DATA_DIR || "/data";
if (!isAbsolute(dataDir)) {
  console.error(`[entrypoint] FLYX_DATA_DIR must be absolute (got "${dataDir}")`);
  process.exit(1);
}
const envPath = join(dataDir, ".env");

function parseEnv(raw) {
  const vars = {};
  for (const line of raw.split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const eq = t.indexOf("=");
    if (eq === -1) continue;
    vars[t.slice(0, eq)] = t.slice(eq + 1);
  }
  return vars;
}

const secret = (bytes) => randomBytes(bytes).toString("base64url");

mkdirSync(dataDir, { recursive: true, mode: 0o700 });
const fileVars = existsSync(envPath) ? parseEnv(readFileSync(envPath, "utf-8")) : {};

let changed = false;
if (!fileVars.JWT_SECRET && !process.env.JWT_SECRET) {
  fileVars.JWT_SECRET = secret(48);
  changed = true;
  console.log("[entrypoint] generated JWT_SECRET");
}
if (!fileVars.HOST_KEY && !process.env.HOST_KEY) {
  fileVars.HOST_KEY = secret(18);
  changed = true;
  console.log(`[entrypoint] generated HOST_KEY (see ${envPath})`);
}
if (changed) {
  let content = "# Flyx environment — generated by docker-entrypoint\n\n";
  for (const [k, v] of Object.entries(fileVars)) {
    if (!ENV_KEY_RE.test(k) || isBlocked(k) || /[\r\n\0]/.test(v)) continue;
    content += `${k}=${v}\n`;
  }
  const tmp = `${envPath}.tmp`;
  writeFileSync(tmp, content, { encoding: "utf-8", mode: 0o600 });
  chmodSync(tmp, 0o600);
  renameSync(tmp, envPath);
}

const env = { ...process.env };
for (const [k, v] of Object.entries(fileVars)) {
  if (!ENV_KEY_RE.test(k) || isBlocked(k)) continue;
  if (env[k] === undefined || env[k] === "") env[k] = v;
}
env.FLYX_DATA_DIR = dataDir;

const require = createRequire(join(process.cwd(), "package.json"));
const nextBin = require.resolve("next/dist/bin/next");
const port = String(env.PORT || "3000");
const host = env.HOSTNAME || "0.0.0.0";

const child = spawn(process.execPath, [nextBin, "start", "--port", port, "--hostname", host], {
  env,
  stdio: "inherit",
});
for (const sig of ["SIGTERM", "SIGINT"]) {
  process.on(sig, () => child.kill(sig));
}
child.on("exit", (code, signal) => process.exit(code ?? (signal ? 1 : 0)));
